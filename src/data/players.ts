/**
 * Picks a strong, balanced 5v5 AI squad from the remaining footballers
 * not chosen by the player: [1 GK, 1 DEF, 1 MID, 2 FWD].
 */
export function buildOpponentSquad(homeSquadIds: readonly string[]): FootballerProfile[] {
  const used = new Set(homeSquadIds);
  const available = FOOTBALLERS.filter((p) => !used.has(p.id));

  const pickByGroup = (group: FootballerProfile['positionGroup'], count: number): FootballerProfile[] => {
    const groupPool = available
      .filter((p) => p.positionGroup === group && !pickedIds.has(p.id))
      .sort((a, b) => b.overall - a.overall);
    const chosen: FootballerProfile[] = [];
    for (let i = 0; i < count && i < groupPool.length; i++) {
      chosen.push(groupPool[i]);
      pickedIds.add(groupPool[i].id);
    }
    return chosen;
  };

  const pickedIds = new Set<string>();
  const gk = pickByGroup('GK', 1);
  const def = pickByGroup('DEF', 1);
  const mid = pickByGroup('MID', 1);
  const fwd = pickByGroup('FWD', 2);

  const squad = [...gk, ...def, ...mid, ...fwd];

  // Fallback fill if user picked unusual positions
  for (const p of available) {
    if (squad.length >= 5) break;
    if (!pickedIds.has(p.id)) {
      squad.push(p);
      pickedIds.add(p.id);
    }
  }

  return squad.slice(0, 5);
}

