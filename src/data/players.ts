export const FOOTBALLER_MAP: Record<string, FootballerProfile> = Object.fromEntries(
  FOOTBALLERS.map((p) => [p.id, p])
);

export function getFootballerById(id: string): FootballerProfile {
  const found = FOOTBALLER_MAP[id];
  if (!found) {
    throw new Error(`Unknown footballer id: ${id}`);
  }
  return found;
}

